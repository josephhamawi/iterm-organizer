"""Install, remove and inspect the launchd agent.

Kept in Python rather than shell so the plist is generated by a pure function
that can be tested, and so the .app and the CLI share one implementation.
"""

from __future__ import annotations

import os
import plistlib
import subprocess
import time
from typing import Any

from . import model
from .model import Store

LABEL = "com.rami.iterm-organizer"

# Connecting to the iTerm2 API needs an auth cookie that the iterm2 library
# requests over AppleScript. For a launchd job with no bundle identity that
# request blocks forever on a TCC Automation prompt that never surfaces, and
# iTerm2 rejects cookieless connections with a 401, so there is no fallback.
# Attributing the agent to iTerm2's bundle is what lets the request through.
ITERM_BUNDLE_ID = "com.googlecode.iterm2"


def plist_path(label: str = LABEL) -> str:
    return os.path.expanduser(f"~/Library/LaunchAgents/{label}.plist")


def plist_dict(program: str, store_root: str, label: str = LABEL) -> dict[str, Any]:
    """The launchd job definition.

    KeepAlive uses SuccessfulExit=false so the daemon is restarted when it
    exits non-zero (the iTerm2 connection closed, so reconnect) and left down
    when it exits zero (another instance already holds the lock).
    """
    return {
        "Label": label,
        "ProgramArguments": [program, "--daemon"],
        "AssociatedBundleIdentifiers": [ITERM_BUNDLE_ID],
        "RunAtLoad": True,
        "KeepAlive": {"SuccessfulExit": False},
        "ThrottleInterval": 20,
        "ProcessType": "Background",
        "StandardOutPath": os.path.join(store_root, "launchd.out.log"),
        "StandardErrorPath": os.path.join(store_root, "launchd.err.log"),
    }


def plist_xml(program: str, store_root: str, label: str = LABEL) -> bytes:
    return plistlib.dumps(plist_dict(program, store_root, label))


def _launchctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["/bin/launchctl", *args], capture_output=True, text=True, timeout=30
    )


def domain(label: str = LABEL) -> str:
    return f"gui/{os.getuid()}/{label}"


def install(program: str, store: Store | None = None, label: str = LABEL) -> None:
    """Write the plist and (re)load the agent."""
    store = store or Store()
    store.ensure()
    path = plist_path(label)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    model.write_atomic(path, plist_xml(program, store.root, label).decode("utf-8"))
    _launchctl("bootout", domain(label))  # ignore failure: may not be loaded
    result = _launchctl("bootstrap", f"gui/{os.getuid()}", path)
    if result.returncode != 0:
        raise RuntimeError(
            f"launchctl bootstrap failed ({result.returncode}): "
            f"{result.stderr.strip() or result.stdout.strip()}"
        )
    _launchctl("enable", domain(label))


def uninstall(label: str = LABEL) -> None:
    _launchctl("bootout", domain(label))
    try:
        os.unlink(plist_path(label))
    except FileNotFoundError:
        pass


def parse_launchctl_print(output: str) -> dict[str, str]:
    """Pull the few fields we care about out of `launchctl print` output."""
    fields: dict[str, str] = {}
    for line in output.splitlines():
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        if key in ("state", "pid", "last exit code") and key not in fields:
            fields[key] = value.strip()
    return fields


def status(store: Store | None = None, label: str = LABEL) -> dict[str, Any]:
    store = store or Store()
    result = _launchctl("print", domain(label))
    loaded = result.returncode == 0
    fields = parse_launchctl_print(result.stdout) if loaded else {}
    snapshot, note = store.load()
    return {
        "loaded": loaded,
        "state": fields.get("state", ""),
        "pid": fields.get("pid", ""),
        "note": note,
        "windows": len(snapshot.windows) if snapshot else 0,
        "panes": model.count_panes(snapshot) if snapshot else 0,
        "captured_at": snapshot.created_at if snapshot else 0.0,
        "snapshots": len(store.list_sessions()),
    }


def describe_status(info: dict[str, Any]) -> str:
    """A short human-readable status block, used by the app dialog and --status."""
    lines = []
    if info["loaded"] and info["state"] == "running":
        lines.append(f"Running (pid {info['pid']}).")
    elif info["loaded"]:
        lines.append(f"Installed but not running (state: {info['state'] or 'unknown'}).")
    else:
        lines.append("Not installed.")
    if info["captured_at"]:
        when = time.strftime("%H:%M:%S", time.localtime(info["captured_at"]))
        lines.append(
            f"Last snapshot {when}: {info['windows']} window(s), "
            f"{info['panes']} pane(s)."
        )
    else:
        lines.append("No snapshot captured yet.")
    lines.append(f"{info['snapshots']} snapshot(s) kept.")
    return "\n".join(lines)


def alert(title: str, message: str) -> None:
    """Show a native dialog. Used when the app is opened from Finder."""
    script = (
        f'display dialog {_as_applescript(message)} '
        f'with title {_as_applescript(title)} '
        f'buttons {{"OK"}} default button "OK" with icon note'
    )
    subprocess.run(
        ["/usr/bin/osascript", "-e", script], capture_output=True, timeout=120
    )


def _as_applescript(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'
